"""Quality gate failures must never turn into successful completion checks."""
import importlib.util
import json
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location("quality", Path(__file__).resolve().parents[1] / "quality.py")
quality = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(quality)


class QualityGateTests(unittest.TestCase):
    def setUp(self):
        self.policy = {"thresholds": {"gocyclo": 20, "gocognit": 30, "dupl": 150},
                       "allowances": {"gocyclo": {}, "gocognit": {}}}

    def test_exit_zero_findings_still_fail(self):
        for name in ("deadcode", "dupl"):
            process = subprocess.CompletedProcess([], 0, "unreachable or duplicated code\n", "")
            self.assertTrue(quality.tool_errors(name, process, self.policy))
            process = subprocess.CompletedProcess([], 0, "", "syntax error\n")
            self.assertTrue(quality.tool_errors(name, process, self.policy))
        self.assertTrue(quality.tool_errors("govulncheck", subprocess.CompletedProcess([], 1, "", "database unavailable"), self.policy))

    def test_complexity_limits_reject_growth_new_outliers_and_stale_limits(self):
        existing = {"internal/policy/policy.go:Evaluate": {"max": 43, "reason": "Existing evaluator"}}
        self.assertEqual(quality.complexity_errors({"internal/policy/policy.go:Evaluate": 43}, existing, 20), [])
        for findings in ({"internal/policy/policy.go:Evaluate": 44},
                         {"internal/policy/policy.go:Evaluate": 42}, {},
                         {"internal/policy/policy.go:Evaluate": 43, "new.go:New": 21}):
            self.assertTrue(quality.complexity_errors(findings, existing, 20))
        with self.assertRaises(ValueError):
            quality.complexity_findings("compiler error")
        self.assertTrue(quality.tool_errors("gocyclo", subprocess.CompletedProcess([], 2, "", "failed"), self.policy))
        self.assertTrue(quality.tool_errors("gocyclo", subprocess.CompletedProcess([], 1, "", ""), self.policy))

    def test_package_graph_excludes_generated_sources_and_test_setup_from_metrics(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            package = root / "internal/app"
            package.mkdir(parents=True)
            (package / "app.go").write_text("package app\n")
            (package / "page_templ.go").write_text("// Code generated by templ - DO NOT EDIT.\npackage app\n")
            data = json.dumps({"Dir": str(package), "GoFiles": ["app.go", "page_templ.go"], "TestGoFiles": ["app_test.go"]})
            with patch.object(quality, "ROOT", root), patch.object(quality.subprocess, "check_output", return_value=data):
                packages, files = quality.package_sources()
            self.assertEqual(packages, ["./internal/app"])
            self.assertEqual(files, ["internal/app/app.go"])

    def test_failed_check_does_not_skip_other_tools_and_summary_is_failed(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            binary = root / "bin"
            binary.mkdir()
            for name in quality.REQUIRED:
                (binary / name).touch()
            (root / "complexity.json").write_text(json.dumps(self.policy))
            specs = {name: {"version": "v1"} for name in sorted(quality.REQUIRED)}
            def run(command, **_):
                output = "duplicate code\n" if Path(command[0]).name == "dupl" else ""
                return subprocess.CompletedProcess(command, 0, output, "")
            with patch.object(quality, "BIN", binary), patch.object(quality, "TOOLS", root), \
                 patch.object(quality, "REPORTS", root / "reports"), patch.object(quality, "versions", return_value=specs), \
                 patch.object(quality, "package_sources", return_value=(["./cmd/app"], ["cmd/app/main.go"])), \
                 patch.object(quality.subprocess, "check_output", return_value="seamgraph"), \
                 patch.object(quality.subprocess, "run", side_effect=run) as scanner, patch("builtins.print"):
                self.assertFalse(quality.check())
            self.assertEqual(scanner.call_count, 8)
            results = json.loads((root / "reports/summary.json").read_text())
            self.assertEqual(set(results), quality.REQUIRED)
            self.assertFalse(results["dupl"]["passed"])
            self.assertTrue(results["govulncheck"]["passed"])

    def test_bad_release_checksum_never_installs_an_executable(self):
        with tempfile.TemporaryDirectory() as directory:
            with patch.object(quality, "BIN", Path(directory)), \
                 patch.object(quality.platform, "system", return_value="Linux"), \
                 patch.object(quality.platform, "machine", return_value="x86_64"), \
                 patch.object(quality, "download", side_effect=[b"0" * 64 + b"  golangci-lint-2.15.0-linux-amd64.tar.gz\n", b"tampered"]):
                with self.assertRaisesRegex(RuntimeError, "checksum"):
                    quality.install_golangci("v2.15.0")
            self.assertFalse((Path(directory) / "golangci-lint").exists())


if __name__ == "__main__":
    unittest.main()
